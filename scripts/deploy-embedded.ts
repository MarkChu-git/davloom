// The fallback deploy for an environment whose network blocks Wrangler's static asset upload
// API: it embeds the Dashboard's build (apps/web/dist/client) in the Worker's own code, which
// serves it with scripts/lib/embedded-assets.ts by the same rules as Workers static assets, and
// deploys that Worker without an `assets` section. The normal deploy, `wrangler deploy` with
// apps/api/wrangler.jsonc (.github/workflows/deploy.yml), stays the way production is deployed;
// docs/ci.md says when to use this one.
//
// Usage, from the repository root after `bun run --filter @davloom/web build`:
//   bun scripts/deploy-embedded.ts                   generate apps/api/dist/embedded/ only
//   bun scripts/deploy-embedded.ts --dry-run         also bundle it with `wrangler deploy --dry-run`
//   bun scripts/deploy-embedded.ts --deploy [-- …]   also deploy it; arguments after `--` go to
//                                                    `wrangler deploy`
import { readdir } from "node:fs/promises";
import { isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { EmbeddedFile } from "./lib/embedded-assets";

const root = fileURLToPath(new URL("..", import.meta.url));
const apiDir = join(root, "apps/api");
const clientDir = join(root, "apps/web/dist/client");
/** Under dist/, which git ignores. */
export const outDir = join(apiDir, "dist/embedded");

const TEXT = /^(text\/|application\/(javascript|json|xml|manifest\+json)|image\/svg\+xml)/;

/** A file's bytes as text, or null when they are not UTF-8 that decodes back to the same bytes. */
const textOf = (bytes: Uint8Array): string | null => {
  try {
    return new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(bytes);
  } catch {
    return null;
  }
};

/** The files of a build directory by their URL path, with `_headers` kept apart. */
export const embedFiles = async (
  directory: string,
): Promise<{ files: Record<string, EmbeddedFile>; headers: string }> => {
  const files: Record<string, EmbeddedFile> = {};
  let headers = "";
  const entries = await readdir(directory, { recursive: true, withFileTypes: true });
  for (const entry of entries.toSorted((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isFile()) continue;
    const full = join(entry.parentPath, entry.name);
    const path = `/${relative(directory, full).split("\\").join("/")}`;
    const file = Bun.file(full);
    const bytes = new Uint8Array(await file.arrayBuffer());
    // Workers static assets read _headers and _redirects and never serve them.
    if (path === "/_headers") {
      headers = new TextDecoder().decode(bytes);
      continue;
    }
    if (path === "/_redirects") continue;
    const etag = `"${new Bun.CryptoHasher("sha256").update(bytes).digest("hex").slice(0, 32)}"`;
    const text = TEXT.test(file.type) ? textOf(bytes) : null;
    files[path] =
      text === null
        ? { type: file.type, etag, base64: bytes.toBase64() }
        : { type: file.type, etag, text };
  }
  return { files, headers };
};

/** A path of apps/api/wrangler.jsonc, made relative to the generated config's directory. */
const rebased = (path: string) =>
  isAbsolute(path) ? path : relative(outDir, resolve(apiDir, path));

/** apps/api/wrangler.jsonc for the embedded Worker: no `assets`, its own entry, paths rebased. */
export const embeddedConfig = (config: unknown): Record<string, unknown> => {
  if (!isRecord(config)) throw new Error("apps/api/wrangler.jsonc holds no object");
  const { assets: _assets, $schema: _schema, ...rest } = config;
  const alias = Object.fromEntries(
    Object.entries(isRecord(rest.alias) ? rest.alias : {}).map(([name, path]) => [
      name,
      typeof path === "string" && path.startsWith(".") ? rebased(path) : path,
    ]),
  );
  const databases = (Array.isArray(rest.d1_databases) ? rest.d1_databases : []).map(
    (database: unknown) =>
      isRecord(database) && typeof database.migrations_dir === "string"
        ? { ...database, migrations_dir: rebased(database.migrations_dir) }
        : database,
  );
  return { ...rest, main: "entry.ts", alias, d1_databases: databases };
};

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

const ENTRY = `// Generated by scripts/deploy-embedded.ts; do not edit.
import { createWorker } from "${relative(outDir, join(apiDir, "src/worker.workers"))}";
import { createAssetServer } from "${relative(outDir, join(root, "scripts/lib/embedded-assets"))}";
import { files, headers } from "./assets.gen";

export { StorageObject } from "@davloom/storage/durable-object";

const assets = createAssetServer(files, headers);
const worker = createWorker(assets);
// The paths the Worker runs first for in apps/api/wrangler.jsonc; the rest are the Dashboard's.
const WORKER_FIRST = /^\\/$|^\\/(api|dav)(\\/|$)/;

export default {
  fetch: (request: Request) =>
    WORKER_FIRST.test(new URL(request.url).pathname) ? worker.fetch(request) : assets(request),
};
`;

const main = async () => {
  const args = process.argv.slice(2);
  const separator = args.indexOf("--");
  const own = separator === -1 ? args : args.slice(0, separator);
  const passed = separator === -1 ? [] : args.slice(separator + 1);
  if (!(await Bun.file(join(clientDir, "index.html")).exists())) {
    console.error("No Dashboard build. Run `bun run --filter @davloom/web build` first.");
    process.exit(1);
  }
  const { files, headers } = await embedFiles(clientDir);
  const config = Bun.JSONC.parse(await Bun.file(join(apiDir, "wrangler.jsonc")).text());
  await Bun.write(
    join(outDir, "assets.gen.ts"),
    `// Generated by scripts/deploy-embedded.ts from apps/web/dist/client; do not edit.\n` +
      `import type { EmbeddedFile } from "${relative(outDir, join(root, "scripts/lib/embedded-assets"))}";\n` +
      `export const headers: string = ${JSON.stringify(headers)};\n` +
      `export const files: Record<string, EmbeddedFile> = ${JSON.stringify(files)};\n`,
  );
  await Bun.write(join(outDir, "entry.ts"), ENTRY);
  await Bun.write(
    join(outDir, "wrangler.jsonc"),
    `${JSON.stringify(embeddedConfig(config), null, 2)}\n`,
  );
  console.log(`embedded ${Object.keys(files).length} files in ${relative(root, outDir)}/`);

  const wrangler = (extra: string[]) => {
    const command = ["bunx", "--bun", "wrangler", "deploy", "--config", "wrangler.jsonc", ...extra];
    console.log(`$ ${command.join(" ")}`);
    const run = Bun.spawnSync(command, { cwd: outDir, stdio: ["inherit", "inherit", "inherit"] });
    if (run.exitCode !== 0) process.exit(run.exitCode ?? 1);
  };
  if (own.includes("--dry-run")) wrangler(["--dry-run", "--outdir", "bundle", ...passed]);
  else if (own.includes("--deploy")) wrangler(passed);
  else console.log(`Deploy it with: bun scripts/deploy-embedded.ts --deploy`);
};

if (import.meta.main) await main();
